#!/usr/bin/env bash
# Download the pinned build tools into .tools/ and write .tools/env.sh.
#
#   scripts/setup-tools.sh
#
# Every download is pinned by version and SHA-256:
#   * Silicon Labs slc-cli 6.0.22, its Python 3.10.3 adapter pack and a Java 21 runtime
#     (Silicon Labs update site, the same files the Nabu Casa silabs-firmware-builder pins)
#   * Arm GNU Toolchain 12.2.rel1 arm-none-eabi (the GCC that GSDK 4.4.0 is qualified with)
#   * pygbl 1.2.0 in a Python virtual environment (GBL packaging)
#
# Set ARM_GCC_DIR to use an arm-none-eabi toolchain already on the machine instead
# (the directory that contains bin/arm-none-eabi-gcc, e.g. /usr).
#
# The cross compiler for the AP binaries (arm-linux-gnueabi-gcc) and cmake come from the
# distribution: apt install gcc-arm-linux-gnueabi cmake
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TOOLS="$ROOT/.tools"
DL="$TOOLS/dl"
SILABS=https://updates.silabs.com/studio/v6/updates/update_site/archives
ARMGNU=https://developer.arm.com/-/media/Files/downloads/gnu/12.2.rel1/binrel

case "$(uname -m)" in
  x86_64)
    SLC_URL=$SILABS/slc-cli/6.0.22/slc-cli.linux.gtk.x86_64.zip
    SLC_SHA=f05e078b369d7e7dbfa31bdd2ad8edf61f04a9291393deab4702137639ba7d19
    PY_URL=$SILABS/python/3.10.3/python.3.10.3.gtk.linux.x86_64.zip
    PY_SHA=26f56b1cfa05b2b3b7dafb2c2a5e3c19498389c34dfe68be800f71f476c86363
    JRE_URL=$SILABS/java21/21.0.6/linux.x86_64_21.0.6.zip
    JRE_SHA=5382fa98bcc66fc3aef48792a3e84328eca16afa9bf97517527e92812516ee50
    GCC_URL=$ARMGNU/arm-gnu-toolchain-12.2.rel1-x86_64-arm-none-eabi.tar.xz
    GCC_SHA=84be93d0f9e96a15addd490b6e237f588c641c8afdf90e7610a628007fc96867
    ;;
  aarch64)
    SLC_URL=$SILABS/slc-cli/6.0.22/slc-cli.linux.gtk.aarch64.zip
    SLC_SHA=5d13e09e605e5dfb94abeb0773055647764bb30d746916f3fc3991a48282a6ba
    PY_URL=$SILABS/python/3.10.3/python.3.10.gtk.linux.aarch64.zip
    PY_SHA=0bd0334fead1e3c2647b6c09b9801b214ab3b999e9e6a9d13553ff57c1e04bb2
    JRE_URL=$SILABS/java21/21.0.6/linux.aarch64_21.0.6.zip
    JRE_SHA=61b4be111fe14d7a9138de920047489c679c7a697320cf69d28b23046edbaf73
    GCC_URL=$ARMGNU/arm-gnu-toolchain-12.2.rel1-aarch64-arm-none-eabi.tar.xz
    GCC_SHA=7ee332f7558a984e239e768a13aed86c6c3ac85c90b91d27f4ed38d7ec6b3e8c
    ;;
  *) echo "unsupported host architecture: $(uname -m)" >&2; exit 1 ;;
esac

fetch() { # url sha256 file
  local url=$1 sha=$2 out="$DL/$3"
  if [[ -f "$out" ]] && echo "$sha  $out" | sha256sum -c --quiet - 2>/dev/null; then
    return
  fi
  echo "== downloading $url"
  curl -fL --retry 3 -o "$out.part" "$url"
  echo "$sha  $out.part" | sha256sum -c --quiet -
  mv "$out.part" "$out"
}

unpack_zip() { # file dest (strips the single top-level directory)
  local tmp
  tmp="$(mktemp -d)"
  unzip -q "$DL/$1" -d "$tmp"
  rm -rf "$2"
  mkdir -p "$(dirname "$2")"
  if [[ $(find "$tmp" -mindepth 1 -maxdepth 1 | wc -l) -eq 1 && -d "$(find "$tmp" -mindepth 1 -maxdepth 1)" ]]; then
    mv "$(find "$tmp" -mindepth 1 -maxdepth 1)" "$2"
    rmdir "$tmp"
  else
    mv "$tmp" "$2"
  fi
}

mkdir -p "$DL"
fetch "$SLC_URL" "$SLC_SHA" slc-cli.zip
fetch "$PY_URL" "$PY_SHA" python.zip
fetch "$JRE_URL" "$JRE_SHA" java21.zip

unpack_zip slc-cli.zip "$TOOLS/slc-cli"
unpack_zip python.zip "$TOOLS/python"
unpack_zip java21.zip "$TOOLS/java21"
# The Java pack keeps its runtime in a jre/ subdirectory. slc's launcher reads the runtime's
# location from slc_java_loc.txt and silently falls back to any java on PATH if that path is
# wrong, so check it: slc-cli 6 needs Java 21.
JAVA_DIR="$TOOLS/java21/jre"
chmod +x "$TOOLS/slc-cli/slc" "$JAVA_DIR/bin/"* "$TOOLS/python/bin/"* 2>/dev/null || true
JAVA_VERSION="$("$JAVA_DIR/bin/java" -version 2>&1 || true)"
[[ "$JAVA_VERSION" == *'version "21'* ]] || { echo "bundled Java 21 not usable at $JAVA_DIR: $JAVA_VERSION" >&2; exit 1; }
echo "$JAVA_DIR" > "$TOOLS/slc-cli/slc_java_loc.txt"

if [[ -n "${ARM_GCC_DIR:-}" ]]; then
  [[ -x "$ARM_GCC_DIR/bin/arm-none-eabi-gcc" ]] || { echo "ARM_GCC_DIR has no bin/arm-none-eabi-gcc: $ARM_GCC_DIR" >&2; exit 1; }
  GCC_DIR="$ARM_GCC_DIR"
else
  fetch "$GCC_URL" "$GCC_SHA" arm-gnu-toolchain.tar.xz
  rm -rf "$TOOLS/arm-gnu-toolchain"
  mkdir -p "$TOOLS/arm-gnu-toolchain"
  tar -xJf "$DL/arm-gnu-toolchain.tar.xz" -C "$TOOLS/arm-gnu-toolchain" --strip-components=1
  GCC_DIR="$TOOLS/arm-gnu-toolchain"
fi

echo "== python venv with pygbl"
rm -rf "$TOOLS/venv"
if command -v uv >/dev/null; then
  uv venv --quiet --python ">=3.11" "$TOOLS/venv"
  uv pip install --quiet --python "$TOOLS/venv/bin/python" -r "$ROOT/firmware/requirements.txt"
elif python3 -m venv "$TOOLS/venv" >/dev/null 2>&1; then
  "$TOOLS/venv/bin/pip" install --quiet --disable-pip-version-check -r "$ROOT/firmware/requirements.txt"
else
  echo "install uv (preferred) or python3-venv" >&2
  exit 1
fi

cat > "$TOOLS/env.sh" <<EOF
# Generated by scripts/setup-tools.sh
export SLC="$TOOLS/slc-cli/slc"
export SLC_TOOL_PATHS="--tool-path $TOOLS/slc-cli --tool-path $TOOLS/python"
export ARM_GCC_DIR="$GCC_DIR"
export OBJCOPY="$GCC_DIR/bin/arm-none-eabi-objcopy"
export PYTHON="$TOOLS/venv/bin/python"
EOF

SLC_VERSION="$("$TOOLS/slc-cli/slc" --version 2>&1)" || { echo "slc failed: $SLC_VERSION" >&2; exit 1; }
GCC_VERSION="$("$GCC_DIR/bin/arm-none-eabi-gcc" --version)"
echo "== tools ready"
echo "slc ${SLC_VERSION%%$'\n'*}"
echo "${GCC_VERSION%%$'\n'*}"
